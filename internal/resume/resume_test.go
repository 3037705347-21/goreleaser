func TestFinalizeRemovesUnclaimedAndPrunes(t *testing.T) {
	dist := t.TempDir()
	writeMetadata(t, dist, testVersion)

	// adopted binary, which the build pipe will claim
	bin := binaryArtifact(t, dist, "foo", "linux_amd64_v1", "foo")

	// adopted archive that no pipe reaffirms (platform removed from
	// archives at runtime)
	oldArchive := filepath.Join(dist, "foo_1.0.0_linux_386.tar.gz")
	writeFile(t, oldArchive, "old")
	arch := &artifact.Artifact{
		Name:   "foo_1.0.0_linux_386.tar.gz",
		Path:   oldArchive,
		Type:   artifact.UploadableArchive,
		Goos:   "linux",
		Goarch: "386",
		Extra:  artifact.Extras{artifact.ExtraID: "default"},
	}

	// fresh archive produced by this run (not in the previous manifest)
	newArchive := filepath.Join(dist, "foo_1.0.0_linux_amd64.tar.gz")
	writeFile(t, newArchive, "new")
	fresh := &artifact.Artifact{
		Name:   "foo_1.0.0_linux_amd64.tar.gz",
		Path:   newArchive,
		Type:   artifact.UploadableArchive,
		Goos:   "linux",
		Goarch: "amd64",
		Extra:  artifact.Extras{artifact.ExtraID: "default"},
	}

	writeArtifactsFile(t, dist, []*artifact.Artifact{bin, arch})

	ctx := testctx.WrapWithCfg(t.Context(), testProject(dist), testctx.WithVersion(testVersion))
	engaged, err := Detect(ctx)
	require.NoError(t, err)
	require.True(t, engaged)

	// build pipe claims the binary; the new archive is not adopted so it
	// needs no claiming. The old archive stays unclaimed.
	for _, a := range ctx.Artifacts.List() {
		if a.Type == artifact.Binary {
			Claim(ctx, a)
		}
	}
	// the freshly produced archive is added to the artifact list too
	ctx.Artifacts.Add(fresh)

	require.NoError(t, Finalize(ctx))

	_, err = os.Stat(oldArchive)
	require.True(t, os.IsNotExist(err))
	_, err = os.Stat(newArchive)
	require.NoError(t, err)
	_, err = os.Stat(filepath.Join(dist, "foo_linux_amd64_v1", "foo"))
	require.NoError(t, err)

	names := map[string]bool{}
	for _, a := range ctx.Artifacts.List() {
		names[a.Name] = true
	}
	require.False(t, names["foo_1.0.0_linux_386.tar.gz"])
	require.True(t, names["foo_1.0.0_linux_amd64.tar.gz"])

	// idempotent: a second run converges to the same result
	require.NoError(t, Finalize(ctx))
	_, err = os.Stat(newArchive)
	require.NoError(t, err)
}

func TestCheckpointStripsAdoptedMarker(t *testing.T) {
	dist := t.TempDir()
	require.NoError(t, os.MkdirAll(dist, 0o755))
	ctx := testctx.WrapWithCfg(t.Context(), config.Project{Dist: dist}, testctx.WithVersion(testVersion))
	ctx.Resume = true
	a := &artifact.Artifact{
		Name:  "foo",
		Path:  filepath.Join(dist, "foo"),
		Type:  artifact.Binary,
		Extra: artifact.Extras{artifact.ExtraID: "foo", artifact.ExtraAdopted: true},
	}
	ctx.Artifacts.Add(a)

	require.NoError(t, Checkpoint(ctx))

	bts, err := os.ReadFile(filepath.Join(dist, ArtifactsFile))
	require.NoError(t, err)
	require.NotContains(t, string(bts), artifact.ExtraAdopted)

	reloaded, err := ReadArtifacts(dist)
	require.NoError(t, err)
	require.Len(t, reloaded, 1)
	require.Equal(t, artifact.Binary, reloaded[0].Type)
	require.False(t, Adopted(ctx, reloaded[0]))
	_, hasMarker := reloaded[0].Extra[artifact.ExtraAdopted]
	require.False(t, hasMarker)
}

