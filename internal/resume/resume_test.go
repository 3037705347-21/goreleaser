const testVersion = "1.0.0"

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
}

func writeMetadata(t *testing.T, dist, version string) {
	t.Helper()
	bts, err := json.Marshal(priorMetadata{ProjectName: "foo", Version: version})
	require.NoError(t, err)
	writeFile(t, filepath.Join(dist, MetadataFile), string(bts))
}

func writeArtifactsFile(t *testing.T, dist string, arts []*artifact.Artifact) {
	t.Helper()
	bts, err := json.Marshal(arts)
	require.NoError(t, err)
	writeFile(t, filepath.Join(dist, ArtifactsFile), string(bts))
}

func binaryArtifact(t *testing.T, dist, id, target, name string) *artifact.Artifact {
	t.Helper()
	path := filepath.Join(dist, id+"_"+target, name)
	writeFile(t, path, "binary:"+target)
	return &artifact.Artifact{
		Name:   name,
		Path:   path,
		Type:   artifact.Binary,
		Target: target,
		Extra: artifact.Extras{
			artifact.ExtraID:      id,
			artifact.ExtraBuilder: "go",
		},
	}
}

func testProject(dist string) config.Project {
	return config.Project{
		ProjectName: "foo",
		Dist:        dist,
		Builds: []config.Build{
			{
				ID:      "foo",
				Builder: "go",
				Targets: []string{"linux_amd64_v1", "linux_arm64_v8.0"},
			},
		},
		Archives: []config.Archive{
			{ID: "default"},
		},
	}
}

func TestDetectFreshDirectories(t *testing.T) {
	t.Run("missing", func(t *testing.T) {
		dist := filepath.Join(t.TempDir(), "dist")
		ctx := testctx.WrapWithCfg(t.Context(), config.Project{Dist: dist}, testctx.WithVersion(testVersion))
		engaged, err := Detect(ctx)
		require.NoError(t, err)
		require.False(t, engaged)
		require.False(t, ctx.Resume)
	})

	t.Run("empty", func(t *testing.T) {
		dist := t.TempDir()
		ctx := testctx.WrapWithCfg(t.Context(), config.Project{Dist: dist}, testctx.WithVersion(testVersion))
		engaged, err := Detect(ctx)
		require.NoError(t, err)
		require.False(t, engaged)
	})

	t.Run("files without metadata", func(t *testing.T) {
		dist := t.TempDir()
		writeFile(t, filepath.Join(dist, "mybin"), "manual")
		ctx := testctx.WrapWithCfg(t.Context(), config.Project{Dist: dist}, testctx.WithVersion(testVersion))
		engaged, err := Detect(ctx)
		require.NoError(t, err)
		require.False(t, engaged)
		// manual file is left in place
		_, err = os.Stat(filepath.Join(dist, "mybin"))
		require.NoError(t, err)
	})

	t.Run("different version", func(t *testing.T) {
		dist := t.TempDir()
		writeMetadata(t, dist, "0.9.0")
		writeFile(t, filepath.Join(dist, "foo_linux_amd64_v1", "foo"), "old")
		ctx := testctx.WrapWithCfg(t.Context(), testProject(dist), testctx.WithVersion(testVersion))
		engaged, err := Detect(ctx)
		require.NoError(t, err)
		require.False(t, engaged)
		require.False(t, ctx.Resume)
	})

	t.Run("partial builds never resume", func(t *testing.T) {
		dist := t.TempDir()
		writeMetadata(t, dist, testVersion)
		ctx := testctx.WrapWithCfg(t.Context(), testProject(dist),
			testctx.WithVersion(testVersion),
			testctx.Partial,
		)
		engaged, err := Detect(ctx)
		require.NoError(t, err)
		require.False(t, engaged)
	})
}

func TestDetectAdoptsMatchingArtifacts(t *testing.T) {
	dist := t.TempDir()
	writeMetadata(t, dist, testVersion)

	amd64 := binaryArtifact(t, dist, "foo", "linux_amd64_v1", "foo")
	arm64 := binaryArtifact(t, dist, "foo", "linux_arm64_v8.0", "foo")

	archivePath := filepath.Join(dist, "foo_1.0.0_linux_amd64.tar.gz")
	writeFile(t, archivePath, "archive")
	arch := &artifact.Artifact{
		Name:   "foo_1.0.0_linux_amd64.tar.gz",
		Path:   archivePath,
		Type:   artifact.UploadableArchive,
		Goos:   "linux",
		Goarch: "amd64",
		Extra: artifact.Extras{
			artifact.ExtraID:     "default",
			artifact.ExtraFormat: "tar.gz",
		},
	}

	// derived artifacts are regenerated by their own pipes
	checksumPath := filepath.Join(dist, "foo_1.0.0_checksums.txt")
	writeFile(t, checksumPath, "checksums")
	checksum := &artifact.Artifact{
		Name: "foo_1.0.0_checksums.txt",
		Path: checksumPath,
		Type: artifact.Checksum,
	}

	// a manually placed file must survive
	manualPath := filepath.Join(dist, "notes.txt")
	writeFile(t, manualPath, "manual")

	writeArtifactsFile(t, dist, []*artifact.Artifact{amd64, arm64, arch, checksum})

	ctx := testctx.WrapWithCfg(t.Context(), testProject(dist), testctx.WithVersion(testVersion))
	engaged, err := Detect(ctx)
	require.NoError(t, err)
	require.True(t, engaged)
	require.True(t, ctx.Resume)

	// binaries and archive adopted and marked
	require.Len(t, ctx.Artifacts.List(), 3)
	for _, a := range ctx.Artifacts.List() {
		require.True(t, Adopted(ctx, a), "expected %s to be adopted", a.Name)
	}

	// adopted files kept
	for _, p := range []string{
		filepath.Join(dist, "foo_linux_amd64_v1", "foo"),
		filepath.Join(dist, "foo_linux_arm64_v8.0", "foo"),
		archivePath,
		manualPath,
	} {
		_, err := os.Stat(p)
		require.NoError(t, err, "expected %s to be kept", p)
	}

	// derived artifacts removed so their pipes regenerate them
	_, err = os.Stat(checksumPath)
	require.True(t, os.IsNotExist(err))

	// owned list remembers everything the previous run produced
	require.Contains(t, ctx.ResumeOwned, checksumPath)
	require.NotContains(t, ctx.ResumeOwned, manualPath)
}

func TestDetectRemovesArtifactsOfRemovedTargets(t *testing.T) {
	dist := t.TempDir()
	writeMetadata(t, dist, testVersion)

	keep := binaryArtifact(t, dist, "foo", "linux_amd64_v1", "foo")
	gone := binaryArtifact(t, dist, "foo", "linux_386_sse2", "foo")

	// archive id removed from the configuration
	oldArchive := filepath.Join(dist, "foo_1.0.0_linux_386.tar.gz")
	writeFile(t, oldArchive, "oldarchive")
	arch := &artifact.Artifact{
		Name:   "foo_1.0.0_linux_386.tar.gz",
		Path:   oldArchive,
		Type:   artifact.UploadableArchive,
		Goos:   "linux",
		Goarch: "386",
		Extra:  artifact.Extras{artifact.ExtraID: "removed"},
	}

	// manual file inside the removed target directory keeps it alive
	manualInGoneDir := filepath.Join(dist, "foo_linux_386_sse2", "manual.txt")
	writeFile(t, manualInGoneDir, "manual")

	writeArtifactsFile(t, dist, []*artifact.Artifact{keep, gone, arch})

	cfg := testProject(dist)
	ctx := testctx.WrapWithCfg(t.Context(), cfg, testctx.WithVersion(testVersion))
	engaged, err := Detect(ctx)
	require.NoError(t, err)
	require.True(t, engaged)

	// only the amd64 binary is adopted
	adopted := ctx.Artifacts.List()
	require.Len(t, adopted, 1)
	require.Equal(t, "linux_amd64_v1", adopted[0].Target)

	// obsolete binary file is gone, but the manual file keeps the directory
	_, err = os.Stat(filepath.Join(dist, "foo_linux_386_sse2", "foo"))
	require.True(t, os.IsNotExist(err))
	_, err = os.Stat(manualInGoneDir)
	require.NoError(t, err)

	// archive whose ID was removed is deleted
	_, err = os.Stat(oldArchive)
	require.True(t, os.IsNotExist(err))

	// kept target untouched
	_, err = os.Stat(filepath.Join(dist, "foo_linux_amd64_v1", "foo"))
	require.NoError(t, err)
}

